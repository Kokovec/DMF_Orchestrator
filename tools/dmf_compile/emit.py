"""workloads/generated/<id>.yaml, <id>.config.json and <id>.source.xml, written atomically.

workloads/generated/ is git-ignored build output; hand-written workloads stay in workloads/<id>.yaml.
scripts/workload-file.sh resolves an id to one or the other.

Literal formats other scripts rely on (04-orchestrator-spec.md):
- scripts/windows-browser.sh takes the first line matching `^ *hostname:`;
- scripts/facility.sh expects each function's `- name:` on the line just before its `kind:`.
Strings holding line breaks or tabs are written double-quoted on one line, so no value can
start a line that either awk program would match.
"""
import json
import os
import re
import tempfile
from pathlib import Path

import yaml

HEADER_PREFIX = "# GENERATED by tools/dmf_compile"


class Flow(dict):
    """A mapping written in flow style: {a: 1, b: 2}."""


class FlowList(list):
    """A sequence written in flow style: [a, b]."""


class _Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)   # indent sequences under their key


def _str(dumper, s):
    style = '"' if any(c in s for c in "\n\r\t") or not s.isprintable() else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style=style)


_Dumper.add_representer(str, _str)
_Dumper.add_representer(Flow, lambda d, v: d.represent_mapping("tag:yaml.org,2002:map", v.items(), flow_style=True))
_Dumper.add_representer(FlowList, lambda d, v: d.represent_sequence("tag:yaml.org,2002:seq", v, flow_style=True))


def header(source_name, revision):
    return f"{HEADER_PREFIX} from {source_name} revision {revision}. Do not edit.\n"


def render_yaml(doc, head):
    body = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, default_flow_style=False, allow_unicode=True,
                     width=float("inf"))
    return head + body


# The awk programs in scripts/windows-browser.sh and scripts/facility.sh, as regular expressions.
_HOSTNAME_LINE = re.compile(r"^ *hostname:")
_KIND_SWITCHFRAME = re.compile(r"^ *kind: *switchframe *$")


def literal_format_problems(text, doc):
    """Checks the generated text the way both scripts read it."""
    problems = []
    lines = text.splitlines()
    host = next((ln.split()[1] for ln in lines if _HOSTNAME_LINE.match(ln)), None)
    if host != doc["spec"]["access"]["hostname"]:
        problems.append(f"scripts/windows-browser.sh would read hostname {host!r}")
    prev, mixers = None, []
    for ln in lines:
        if _KIND_SWITCHFRAME.search(ln):
            mixers.append(prev)
        f = ln.split()
        if len(f) >= 3 and f[0] == "-" and f[1] == "name:":
            prev = f[2]
    want = [f["name"] for f in doc["spec"]["functions"] if f.get("kind") == "switchframe"]
    if mixers != want:
        problems.append(f"scripts/facility.sh would read the mixer as {mixers!r}")
    return problems


def render_json(config):
    return json.dumps(config, indent=2, ensure_ascii=False) + "\n"


GENERATED_DIR = Path("workloads") / "generated"


def hand_written(repo, workload_id):
    return Path(repo) / "workloads" / f"{workload_id}.yaml"


def paths(repo, workload_id):
    base = Path(repo) / GENERATED_DIR
    return {"yaml": base / f"{workload_id}.yaml", "config": base / f"{workload_id}.config.json",
            "source": base / f"{workload_id}.source.xml"}


def _atomic_write(path, data: bytes):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        os.unlink(tmp)
        raise


def write(repo, workload_id, yaml_text, config_text, source_bytes):
    """The workload YAML goes last: until it's replaced, the old revision stays complete."""
    p = paths(repo, workload_id)
    _atomic_write(p["config"], config_text.encode())
    _atomic_write(p["source"], source_bytes)
    _atomic_write(p["yaml"], yaml_text.encode())
    return [p["yaml"], p["config"], p["source"]]
