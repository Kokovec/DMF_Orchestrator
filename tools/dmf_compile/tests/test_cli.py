import http.server
import json
import threading
import unittest
from unittest import mock

from tools.dmf_compile import facility

from .util import STUDIO_A, RepoTest


class _Handler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        body = STUDIO_A.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", "application/xml; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *a):
        pass


class Cli(RepoTest):
    def test_facility_export(self):
        rc, out, _ = self.repo.cli("facility-export")
        self.assertEqual((rc, out), (0, "wrote .state/facility-local.json\n"))
        exported = json.loads((self.repo.path / ".state" / "facility-local.json").read_text())
        self.assertEqual(exported["name"], "local")
        self.assertEqual(set(exported["capabilities"]), set(facility.CAPABILITIES))
        self.assertIs(exported["capabilities"]["mxl"], True)
        self.assertIs(exported["capabilities"]["gpu"], False)
        self.assertEqual(exported["limits"], {"maxRecordingGiB": 200, "domainsPerWorkload": 1,
                                              "functionsPerWorkload": {"switchframe.1": {"min": 1, "max": 1}}})

    def test_facility_export_fills_in_rule_2_limits_a_profile_leaves_out(self):
        self.repo.facility("nolimits", limits={"maxRecordingGiB": 200})
        rc, _, _ = self.repo.cli("facility-export", "--facility", "nolimits")
        self.assertEqual(rc, 0)
        exported = json.loads((self.repo.path / ".state" / "facility-nolimits.json").read_text())
        self.assertEqual(exported["limits"]["functionsPerWorkload"], {"switchframe.1": {"min": 1, "max": 1}})
        self.assertEqual(exported["limits"]["domainsPerWorkload"], 1)

    def test_rule_2_limits_the_compiler_cant_build_are_refused(self):
        (self.repo.path / "facility" / "big.yaml").write_text(
            "apiVersion: dmf.local/v1alpha1\nkind: Facility\nmetadata: {name: big}\nspec:\n  baseDomain: dmf.test\n"
            "  workloadUids: {first: 1, last: 2}\n  ports: {quic: {first: 1, last: 2}, srt: {first: 1, last: 2}}\n"
            "  capabilities: {mxl: true}\n  limits:\n    domainsPerWorkload: 2\n"
            "    functionsPerWorkload: {switchframe.1: {min: 1, max: 2}, acme.1: {max: 1}, dmf-mxl.1: {min: 3, max: 1}}\n")
        rc, _, err = self.repo.cli("facility-export", "--facility", "big")
        self.assertEqual(rc, 1)
        for text in ("functionsPerWorkload.switchframe.1 must be {min: 1, max: 1}", "functionsPerWorkload.acme.1 is not "
                     "a function type", "functionsPerWorkload.dmf-mxl.1 must be {min, max}", "domainsPerWorkload must be 1"):
            self.assertIn(text, err)

    def test_bad_facility_profile(self):
        (self.repo.path / "facility" / "bad.yaml").write_text(
            "apiVersion: dmf.local/v1alpha1\nkind: Facility\nmetadata: {name: bad}\nspec:\n  baseDomain: DMF_test\n"
            "  workloadUids: {first: 2, last: 1}\n  ports: {quic: {first: 1, last: 2}, srt: {first: 1, last: 2}}\n"
            "  capabilities: {warp-drive: true, mxl: yes-please}\n")
        rc, _, err = self.repo.cli("facility-export", "--facility", "bad")
        self.assertEqual(rc, 1)
        for text in ("baseDomain 'DMF_test' is not a DNS name", "spec.workloadUids must have integer first <= last",
                     "capabilities.warp-drive is not a capability", "capabilities.mxl must be true or false"):
            self.assertIn(text, err)

    def test_remote_url_needs_allow_remote(self):
        with mock.patch("urllib.request.urlopen") as urlopen:
            rc, _, err = self.repo.cli("compile", "https://toolkit.example.com/api/workloads/studio-a/published.xml")
            urlopen.assert_not_called()
        self.assertEqual(rc, 1)
        self.assertIn("only http://localhost URLs are read; set ALLOW_REMOTE=1", err)

    def test_localhost_url(self):
        server = http.server.HTTPServer(("127.0.0.1", 0), _Handler)
        threading.Thread(target=server.serve_forever, daemon=True).start()
        self.addCleanup(server.server_close)
        self.addCleanup(server.shutdown)
        url = f"http://localhost:{server.server_port}/api/workloads/studio-a/published.xml"
        rc, out, err = self.repo.cli("compile", url)
        self.assertEqual((rc, err), (0, ""))
        self.assertIn("wrote workloads/generated/studio-a.yaml", out)
        head = (self.repo.gen / "studio-a.yaml").read_text().splitlines()[0]
        self.assertEqual(head, f"# GENERATED by tools/dmf_compile from {url} revision 1. Do not edit.")

    def test_missing_file(self):
        rc, _, err = self.repo.cli("compile", "examples/nope.xml")
        self.assertEqual(rc, 1)
        self.assertIn("No such file or directory", err)

    def test_release(self):
        self.repo.cli("compile", "examples/studio-a.workload.xml")
        self.assertEqual(self.repo.cli("release", "studio-a")[1], "released studio-a\n")
        self.assertEqual(self.repo.cli("release", "studio-a")[1], "no allocation for studio-a\n")


if __name__ == "__main__":
    unittest.main()
