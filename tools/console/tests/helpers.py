class Audit:
    """Records every file this process opens and every subprocess it starts (sys.audit events).

    An audit hook can't be removed, so one is installed for the whole test run and switched on
    and off around the code under test.
    """
    events = []
    on = False

    @classmethod
    def hook(cls, event, args):
        if not cls.on:
            return
        if event == "open":
            path, mode, flags = args
            cls.events.append(("open", str(path), mode, flags))
        elif event == "subprocess.Popen":
            cls.events.append(("exec", [str(a) for a in args[1]]))
        elif event == "os.posix_spawn":
            cls.events.append(("exec", [str(a) for a in args[1]]))

    @classmethod
    def start(cls):
        cls.events = []
        cls.on = True

    @classmethod
    def stop(cls):
        cls.on = False
        return list(cls.events)

    @staticmethod
    def writes(events):
        """Files opened for writing, other than devices (the PTY master is /dev/ptmx)."""
        out = []
        for e in events:
            if e[0] != "open":
                continue
            _, path, mode, flags = e
            writing = (mode and any(c in mode for c in "wax+")) or (isinstance(flags, int) and flags & (
                os.O_WRONLY | os.O_RDWR | os.O_CREAT | os.O_APPEND | os.O_TRUNC))
            if writing and not path.startswith("/dev/"):
                out.append(path)
        return out


sys.addaudithook(Audit.hook)


