def pod(name, ready=True, containers=(("app", None, None),), ports=None):
    cs = []
    for cname, cpu_limit, cpu_req in containers:
        res = {}
        if cpu_limit:
            res["limits"] = {"cpu": cpu_limit}
        if cpu_req:
            res["requests"] = {"cpu": cpu_req, "memory": "1Gi"}
        c = {"name": cname, "resources": res}
        if ports and cname in ports:
            c["ports"] = [{"name": cname, "containerPort": ports[cname]}]
        cs.append(c)
    return {"metadata": {"name": name, "namespace": "x"}, "spec": {"containers": cs},
            "status": {"phase": "Running", "conditions": [{"type": "Ready", "status": "True" if ready else "False"}]}}


