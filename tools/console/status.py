"""The console's Status panels (docs/orchestration/05-facility-console.md, Status).

Every check runs without sudo, with its own timeout, and a failing check comes back as
{"state": "unknown", "error": ...} without affecting the others.

What this module must never do (C6 and the spec's Status section), checked by
tests/test_status.py: call SwitchFrame routes that return secrets (/api/output/destinations,
/api/sync/state-snapshot), read .state/secrets/ or anything Terraform writes, or write a file.
The only SwitchFrame-side read is the reconciler's /metrics, which holds counters only.
"""
import asyncio
import datetime as dt
import json
import os
import re
import signal
from pathlib import Path

import aiohttp
import yaml

WORKLOAD_ID = re.compile(r"^[a-z0-9]([-a-z0-9]{0,40}[a-z0-9])?$")  # as scripts/workload-file.sh
ARCHIVE_RUN = re.compile(r"^(?P<id>.+)-(?P<ts>\d{8}T\d{6}Z)$")
HEADER_REVISION = re.compile(r"^# GENERATED by tools/dmf_compile from .* revision (\d+)\. Do not edit\.")
METRIC = re.compile(r"^(dmf_reconcile_(?:api_up|pending|failed))(?:\{[^}]*\})?\s+([0-9.eE+-]+)\s*$")
MXL_ROOT = "/var/lib/dmf/mxl"


class CheckError(Exception):
    """A check's own failure, with a message fit to show on the page."""


class Status:
    def __init__(self, repo, facility="local", toolkit_url="http://localhost:3001", timeout=3.0,
                 env=None, systemd_dir="/etc/systemd/system", distro=None, tools_bin=True):
        self.repo = Path(repo).resolve()
        self.facility = facility
        self.toolkit_url = toolkit_url.rstrip("/")
        self.timeout = timeout
        self.kubeconfig = str(self.repo / ".state" / "kubeconfig")
        self.env = dict(os.environ if env is None else env)
        if tools_bin:  # the pinned kubectl, as make puts it first on PATH
            self.env["PATH"] = f"{self.repo / '.tools' / 'bin'}:{self.env.get('PATH', '/usr/bin:/bin')}"
        self.systemd_dir = Path(systemd_dir)
        self.distro = self.env.get("WSL_DISTRO_NAME", "") if distro is None else distro

    # ---- plumbing ----

    async def run(self, *argv):
        """(returncode, stdout, stderr) of argv, killed with its children after the timeout."""
        proc = await asyncio.create_subprocess_exec(
            *argv, stdin=asyncio.subprocess.DEVNULL, stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE, env=self.env, cwd=self.repo, start_new_session=True)
        try:
            out, err = await asyncio.wait_for(proc.communicate(), self.timeout)
        except asyncio.TimeoutError:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            await proc.wait()
            raise CheckError(f"{Path(argv[0]).name} timed out after {self.timeout:g} s")
        return proc.returncode, out.decode(errors="replace"), err.decode(errors="replace")

    async def kubectl(self, *args):
        rc, out, err = await self.run("kubectl", "--kubeconfig", self.kubeconfig,
                                      f"--request-timeout={self.timeout:g}s", *args)
        if rc != 0:
            # The last line is kubectl's own summary; earlier ones are client-go log lines.
            raise CheckError(last_line(err) or f"kubectl exited {rc}")
        return out

    async def guarded(self, coro, steps=1):
        """A check's result, or unknown with its error: never raises, never runs past its timeout.

        steps: how many calls, each with its own timeout, the check makes one after the other.
        """
        try:
            return await asyncio.wait_for(coro, steps * self.timeout + 0.5)
        except asyncio.TimeoutError:
            return unknown(f"timed out after {self.timeout:g} s")
        except CheckError as e:
            return unknown(str(e))
        except Exception as e:  # a bug in one check must not fail the page
            return unknown(f"{type(e).__name__}: {e}")

    # ---- facility row ----

    async def k3s(self):
        service = "k3s"
        rc, _, _ = await self.run("systemctl", "cat", "k3s")
        if rc != 0:
            service = "k3s-agent"  # as scripts/facility.sh chooses
        rc, out, _ = await self.run("systemctl", "is-active", service)
        state = out.strip() or "unknown"
        return {"state": "ok" if state == "active" else "bad",
                "text": "running" if state == "active" else state, "service": service}

    async def kubernetes(self):
        out = await self.kubectl("get", "ns", "-o", "name")
        return {"state": "ok", "text": "answers", "namespaces": len(out.split())}

    async def keycloak(self):
        domain = self.base_domain()
        url = f"https://keycloak.{domain}/realms/dmf/.well-known/openid-configuration"
        ip = await self.ingress_ip()
        ca = self.repo / ".state" / "dmf-root-ca.crt"
        tls = ["--cacert", str(ca)] if ca.exists() else ["-k"]
        rc, out, err = await self.run("curl", "-s", "-o", "/dev/null", "-w", "%{http_code}",
                                      "--max-time", f"{self.timeout:g}", *tls,
                                      "--resolve", f"keycloak.{domain}:443:{ip}", url)
        code = out.strip()
        if code == "200":
            return {"state": "ok", "text": "ready", "url": url}
        if code in ("", "000"):
            return {"state": "bad", "text": "no answer", "url": url, "error": f"no answer through the ingress at {ip}"}
        return {"state": "bad", "text": f"answers {code}", "url": url}

    async def ingress_ip(self):
        """The address scripts/facility.sh and windows-browser.sh reach the ingress on."""
        try:
            ip = (await self.kubectl("-n", "kube-system", "get", "svc", "traefik", "-o",
                                     "jsonpath={.status.loadBalancer.ingress[0].ip}")).strip()
            if ip:
                return ip
        except CheckError:
            pass
        rc, out, _ = await self.run("ip", "-4", "-o", "addr", "show", "eth0")
        m = re.search(r"inet (\d+\.\d+\.\d+\.\d+)/", out)
        if not m:
            raise CheckError("no ingress address: traefik has none and eth0 has no IPv4 address")
        return m.group(1)

    async def nmos(self):
        pods = json.loads(await self.kubectl("-n", "dmf-system", "get", "pods", "-l",
                                             "app.kubernetes.io/name=nmos-registry", "-o", "json"))["items"]
        if not pods:
            return {"state": "bad", "text": "no pod"}
        if any(pod_ready(p) for p in pods):
            return {"state": "ok", "text": "up"}
        return {"state": "bad", "text": "not ready"}

    async def capacity(self):
        rc, out, err = await self.run("python3", str(self.repo / "ansible" / "scripts" / "capacity.py"),
                                      "--facility", self.kubeconfig, MXL_ROOT)
        if rc != 0:
            # capacity.py lets kubectl's failure through as a traceback; name the call instead.
            m = re.search(r"CalledProcessError: Command '\[.*?'get', '([^']+)'", err)
            raise CheckError(f"capacity.py: kubectl get {m.group(1)} failed (Kubernetes doesn't answer?)" if m
                             else last_line(err) or f"capacity.py exited {rc}")
        data = json.loads(out)
        r, a = data["reserved"], data["allocatable"]
        return {"state": "ok", "text": f"CPU reserved {fmt(r['cpu'])} / {fmt(a['cpu'])}   "
                f"Memory {fmt(r['memory_gib'])} / {fmt(a['memory_gib'])} GiB", "data": data}

    async def mount(self):
        if not self.distro:
            return {"state": "unknown", "error": "WSL_DISTRO_NAME isn't set: not running under WSL"}
        target = f"/mnt/wsl/instances/{self.distro}"
        _, root, _ = await self.run("findmnt", "-n", "-r", "-o", "SOURCE,FSROOT", "--mountpoint", "/")
        rc, here, _ = await self.run("findmnt", "-n", "-r", "-o", "SOURCE,FSROOT", "--mountpoint", target)
        root = last_line(root)
        lines = [line for line in here.splitlines() if line.strip()]
        if rc != 0 or not lines:
            return {"state": "bad", "text": "not mounted", "target": target}
        if root and lines[-1] == root:
            return {"state": "ok", "text": "active", "target": target, "stacked": len(lines)}
        return {"state": "bad", "text": f"something else is mounted there ({lines[-1]})", "target": target}

    async def profile(self):
        src = self.repo / "facility" / f"{self.facility}.yaml"
        out = self.repo / ".state" / f"facility-{self.facility}.json"
        if not out.exists():
            return {"state": "bad", "text": "not exported", "path": rel(out, self.repo)}
        if src.exists() and out.stat().st_mtime < src.stat().st_mtime:
            return {"state": "bad", "text": f"older than facility/{self.facility}.yaml", "path": rel(out, self.repo)}
        return {"state": "ok", "text": "exported", "path": rel(out, self.repo)}

    def base_domain(self):
        with open(self.repo / "facility" / f"{self.facility}.yaml") as fh:
            return yaml.safe_load(fh)["spec"]["baseDomain"]

    # ---- workloads ----

    async def workloads(self):
        """One entry per workload id in any of the four sources the spec names."""
        ids = set()
        for d in (self.repo / "workloads", self.repo / "workloads" / "generated"):
            ids |= {p.stem for p in d.glob("*.yaml")}
        alloc = self.repo / ".state" / "allocations.json"
        if alloc.exists():
            ids |= set(json.loads(alloc.read_text()))

        cluster = await self.guarded(self.cluster_workloads())
        kube_up = cluster.get("state") != "unknown"
        ids |= set(cluster.get("namespaces", {})) if kube_up else set()
        ids = sorted(i for i in ids if WORKLOAD_ID.match(i))

        entries = await asyncio.gather(*(self.workload(i, cluster if kube_up else None) for i in ids))
        # A hand-written file that isn't deployed is an example to copy, such as news-studio: not listed.
        out = {"state": "ok", "items": [w for w in entries if w["deployed"] or w.get("kind") != "hand-written"]}
        if not kube_up:
            out["error"] = f"Kubernetes: {cluster.get('error')}"
        return out

    async def cluster_workloads(self):
        nss, quotas = await asyncio.gather(
            self.kubectl("get", "ns", "-l", "dmf.ebu.ch/workload", "-o", "json"),
            self.kubectl("get", "resourcequota", "-A", "--field-selector", "metadata.name=dmf-reservation", "-o", "json"))
        nss, quotas = json.loads(nss)["items"], json.loads(quotas)["items"]
        cpu = {q["metadata"]["namespace"]: q["spec"].get("hard", {}).get("requests.cpu") for q in quotas}
        namespaces = {}
        for ns in nss:
            labels = ns["metadata"]["labels"]
            wid = labels["dmf.ebu.ch/workload"]
            name = ns["metadata"]["name"]
            # Terraform sets the revision label from the generated header (stage 9); a workload
            # provisioned before that, or a hand-written one, has none.
            rev = labels.get("dmf.ebu.ch/revision")
            namespaces[wid] = {"namespace": name, "cpu": cpu.get(name),
                               "revision": int(rev) if rev and rev.isdigit() else None}
        return {"state": "ok", "namespaces": namespaces}

    async def workload(self, wid, cluster):
        w = {"id": wid, "errors": []}
        rc, out, err = await self.run(str(self.repo / "scripts" / "workload-file.sh"), wid)
        if rc == 0:
            path = Path(out.strip())
            w["file"] = rel(path, self.repo)
            w["kind"] = "compiled" if path.parent.name == "generated" else "hand-written"
            if w["kind"] == "compiled":
                w["revision"] = header_revision(path)
            w["domain"] = flow_domain(path)
        else:
            w["kind"] = "no file"
            w["errors"].append(first_line(err))

        if cluster is None:
            # Kubernetes is down, so namespaces can't be read. A provisioned workload's Flow Domain
            # mount unit (ansible/roles/mxl_domain) stays in place until finalise and is readable
            # without sudo.
            unit = self.systemd_dir / mount_unit(f"{MXL_ROOT}/{w.get('domain') or wid}")
            w["deployed"] = unit.exists()
            w["deployed_from"] = "Flow Domain unit" if unit.exists() else None
            w["state"] = "deployed, stopped" if w["deployed"] else not_deployed(w)
            return w

        ns = cluster["namespaces"].get(wid)
        w["deployed"] = ns is not None
        if not ns:
            w["state"] = not_deployed(w)
            return w
        w["cpu"] = ns["cpu"]
        w["deployed_revision"] = ns.get("revision")
        pods = await self.guarded(self.pods(ns["namespace"]))
        if pods.get("state") == "unknown":
            w["errors"].append(f"pods: {pods['error']}")
            w["state"] = "deployed"
            return w
        w["pods"] = {"ready": pods["ready"], "total": pods["total"]}
        if not pods["total"] or pods["ready"] < pods["total"]:
            w["state"] = "deployed, stopped"
            return w
        w["state"] = "running"
        if pods.get("mixer"):
            m = await self.guarded(self.reconciler(ns["namespace"], *pods["mixer"]))
            if m.get("state") == "unknown":
                w["errors"].append(f"reconciler: {m['error']}")
            else:
                w["reconciler"] = m["metrics"]
                up, pending, failed = (m["metrics"].get(k) for k in ("api_up", "pending", "failed"))
                if failed:
                    w["state"] = f"running, {failed:g} settings failed"
                elif up == 1 and pending == 0 and failed == 0:
                    w["state"] = "on air"
        return w

    async def pods(self, namespace):
        items = json.loads(await self.kubectl("-n", namespace, "get", "pods", "-o", "json"))["items"]
        items = [p for p in items if p.get("status", {}).get("phase") not in ("Succeeded", "Failed")]
        mixer = None
        for p in items:
            names = {c["name"] for c in p["spec"]["containers"]}
            if {"switchframe", "reconciler"} <= names and pod_ready(p):
                port = next((pt["containerPort"] for c in p["spec"]["containers"] if c["name"] == "reconciler"
                             for pt in c.get("ports", []) if pt.get("name") == "reconciler"), 9103)
                mixer = (p["metadata"]["name"], port)
        return {"ready": sum(pod_ready(p) for p in items), "total": len(items), "mixer": mixer}

    async def reconciler(self, namespace, pod, port):
        # As scripts/facility.sh reads the API: curl inside the switchframe container, here for the
        # reconciler's metrics, which share the pod's network.
        out = await self.kubectl("-n", namespace, "exec", pod, "-c", "switchframe", "--",
                                 "curl", "-sf", "--max-time", "2", f"http://127.0.0.1:{int(port)}/metrics")
        metrics = {}
        for line in out.splitlines():
            m = METRIC.match(line)
            if m:
                metrics[m.group(1)[len("dmf_reconcile_"):]] = float(m.group(2))
        if not metrics:
            raise CheckError("the reconciler's /metrics has no dmf_reconcile_ values")
        return {"state": "ok", "metrics": metrics}

    # ---- toolkit designs ----

    async def designs(self, deployed):
        """The toolkit's designs, each with whether it publishes.

        deployed: {id: deployed revision, from the namespace's dmf.ebu.ch/revision label, or None}.
        """
        timeout = aiohttp.ClientTimeout(total=self.timeout)
        try:
            async with aiohttp.ClientSession(timeout=timeout) as s:
                profile = await self.toolkit_profile(s)
                async with s.get(f"{self.toolkit_url}/api/workloads") as r:
                    if r.status != 200:
                        raise CheckError(f"toolkit API answered {r.status} on /api/workloads")
                    listed = (await r.json())["workloads"]
                items = await asyncio.gather(*(self.design(s, d, deployed) for d in listed))
        except (aiohttp.ClientError, OSError, asyncio.TimeoutError) as e:
            port = self.toolkit_url.rsplit(":", 1)[-1]
            return {"state": "bad", "text": f"toolkit API: not reachable on :{port}",
                    "error": str(e) or type(e).__name__, "items": []}
        return {"state": "ok", "text": f"{len(items)} designs", "items": list(items), "profile": profile}

    async def toolkit_profile(self, session):
        """Which facility profile the toolkit server loaded (GET /api/facility: {} without one),
        and whether it is the one this facility exported."""
        async with session.get(f"{self.toolkit_url}/api/facility") as r:
            if r.status != 200:
                return unknown(f"toolkit API answered {r.status} on /api/facility")
            body = await r.json(content_type=None)
        if not isinstance(body, dict) or not body.get("capabilities"):
            return {"state": "bad", "text": "none: the toolkit offers options this facility can't run",
                    "fix": "make facility-export, then restart the toolkit server with DMF_FACILITY set to the "
                           f"exported .state/facility-{self.facility}.json"}
        name = str(body.get("name"))
        exported = self.repo / ".state" / f"facility-{self.facility}.json"
        try:
            ours = json.loads(exported.read_text())
        except (OSError, ValueError):
            ours = None
        if ours is None:
            return {"state": "unknown", "text": name, "name": name,
                    "error": f".state/facility-{self.facility}.json isn't there to compare with"}
        same = name == ours.get("name") and body.get("capabilities") == ours.get("capabilities") \
            and (body.get("limits") or {}) == (ours.get("limits") or {})
        if same:
            return {"state": "ok", "text": name, "name": name}
        return {"state": "bad", "text": f"{name}, not the one exported here", "name": name,
                "fix": f"the toolkit's profile differs from .state/facility-{self.facility}.json: "
                       "restart the toolkit server to load the current export"}

    async def design(self, session, d, deployed):
        wid, rev = str(d["id"]), d.get("revision")
        item = {"id": wid, "name": d.get("name"), "revision": rev, "deployed": wid in deployed}
        if wid in deployed:
            item["deployed_revision"] = deployed[wid]
            if isinstance(rev, int) and isinstance(deployed[wid], int):
                item["newer"] = rev > deployed[wid]
        try:
            async with session.get(f"{self.toolkit_url}/api/workloads/{wid}/published.xml") as r:
                if r.status == 200:
                    item["publishable"] = True
                elif r.status == 422:
                    body = await r.json(content_type=None)
                    item["publishable"] = False
                    item["reasons"] = [d if isinstance(d, str) else json.dumps(d) for d in body.get("details") or []] \
                        or [body.get("error", "not publishable")]
                else:
                    item["error"] = f"published.xml answered {r.status}"
        except (aiohttp.ClientError, OSError, asyncio.TimeoutError) as e:
            item["error"] = f"published.xml: {e or type(e).__name__}"
        return item

    # ---- archive ----

    async def archive(self):
        root = self.repo / ".state" / "archive"
        runs = []
        for d in sorted(root.iterdir()) if root.is_dir() else []:
            m = ARCHIVE_RUN.match(d.name)
            if not d.is_dir() or not m:
                continue
            t = dt.datetime.strptime(m.group("ts"), "%Y%m%dT%H%M%SZ").replace(tzinfo=dt.timezone.utc)
            runs.append({"run": d.name, "id": m.group("id"), "time": t.strftime("%Y-%m-%d %H:%M UTC"),
                         "source_xml": (d / "source.xml").is_file()})
        runs.sort(key=lambda r: r["run"].rsplit("-", 1)[1], reverse=True)
        return {"state": "ok", "items": runs}

    # ---- everything ----

    async def collect(self):
        names = ("k3s", "kubernetes", "keycloak", "nmos", "capacity", "mount", "profile")
        # k3s and mount make two calls in turn, Keycloak finds the ingress address first, and the
        # workloads check reads the cluster, then pods, then metrics: each call has its own timeout.
        steps = {"k3s": 2, "mount": 2, "keycloak": 2}
        results = await asyncio.gather(*(self.guarded(getattr(self, n)(), steps.get(n, 1)) for n in names),
                                       self.guarded(self.workloads(), 4), self.guarded(self.archive()))
        facility = dict(zip(names, results))
        workloads, archive = results[-2], results[-1]
        deployed = {w["id"]: w.get("deployed_revision") for w in workloads.get("items", []) if w.get("deployed")}
        designs = await self.guarded(self.designs(deployed), 3)
        return {"time": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                "facility": facility, "workloads": workloads, "designs": designs, "archive": archive}


def unknown(error):
    return {"state": "unknown", "error": error}


def not_deployed(w):
    return "not deployed" if w.get("kind") == "hand-written" else "compiled"


def pod_ready(p):
    return any(c.get("type") == "Ready" and c.get("status") == "True"
               for c in p.get("status", {}).get("conditions", []))


def header_revision(path):
    with open(path) as fh:
        m = HEADER_REVISION.match(fh.readline())
    return int(m.group(1)) if m else None


def flow_domain(path):
    with open(path) as fh:
        wl = yaml.safe_load(fh)
    return ((wl or {}).get("spec") or {}).get("mediaExchange", {}).get("domain")


def mount_unit(path):
    """systemd-escape --path --suffix=mount, for the characters a Flow Domain path can hold."""
    parts = path.strip("/").split("/")
    return "-".join(p.replace("-", "\\x2d") for p in parts) + ".mount"


def first_line(s):
    return next((line.strip() for line in s.splitlines() if line.strip()), "")


def last_line(s):
    lines = [line.strip() for line in s.splitlines() if line.strip()]
    return lines[-1] if lines else ""


def fmt(x):
    return f"{x:g}" if isinstance(x, (int, float)) else str(x)


def rel(path, root):
    try:
        return str(Path(path).relative_to(root))
    except ValueError:
        return str(path)
